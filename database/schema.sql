--removes all tables and types, so the schema can be re-created from scratch.
DROP TABLE IF EXISTS notifications   CASCADE;
DROP TABLE IF EXISTS ticket_history  CASCADE;
DROP TABLE IF EXISTS tickets         CASCADE;
DROP TABLE IF EXISTS staff_services  CASCADE;
DROP TABLE IF EXISTS services        CASCADE;
DROP TABLE IF EXISTS admins          CASCADE;
DROP TABLE IF EXISTS staff           CASCADE;
DROP TABLE IF EXISTS patients        CASCADE;
DROP TABLE IF EXISTS clinic_settings CASCADE;

--removes types, so they can be re-created from scratch.
DROP TYPE IF EXISTS account_status;
DROP TYPE IF EXISTS queue_status;
DROP TYPE IF EXISTS ticket_status;
DROP TYPE IF EXISTS history_action;
DROP TYPE IF EXISTS notification_type;

-- creates enum types, parang check constraint sa oracle
CREATE TYPE account_status    AS ENUM ('active', 'inactive');
CREATE TYPE queue_status      AS ENUM ('open', 'paused', 'closed');
CREATE TYPE ticket_status     AS ENUM ('waiting', 'serving', 'completed', 'skipped', 'cancelled');
CREATE TYPE history_action    AS ENUM ('created', 'called', 'completed', 'skipped', 'cancelled', 'edited', 'deleted', 'restored', 'expired');
CREATE TYPE notification_type AS ENUM ('near', 'called', 'skipped', 'cancelled', 'paused');

--creates user tables (patients, staff, admins)
CREATE TABLE patients (
    patient_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , full_name            VARCHAR(100)   NOT NULL
  , email                VARCHAR(100)   NOT NULL
  , password_hash        VARCHAR(255)   NOT NULL
  , contact_number       VARCHAR(20)    NULL
  , status               account_status NOT NULL DEFAULT 'active'
  , must_change_password BOOLEAN        NOT NULL DEFAULT FALSE
  , created_at           TIMESTAMPTZ    NOT NULL DEFAULT NOW()
  , CONSTRAINT uq_patients_email UNIQUE (email)
);

CREATE TABLE staff (
    staff_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , full_name            VARCHAR(100)   NOT NULL
  , email                VARCHAR(100)   NOT NULL
  , password_hash        VARCHAR(255)   NOT NULL
  , contact_number       VARCHAR(20)    NULL
  , status               account_status NOT NULL DEFAULT 'active'
  , must_change_password BOOLEAN        NOT NULL DEFAULT FALSE
  , created_at           TIMESTAMPTZ    NOT NULL DEFAULT NOW()
  , CONSTRAINT uq_staff_email UNIQUE (email)
);

CREATE TABLE admins (
    admin_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , full_name            VARCHAR(100)   NOT NULL
  , email                VARCHAR(100)   NOT NULL
  , password_hash        VARCHAR(255)   NOT NULL
  , contact_number       VARCHAR(20)    NULL
  , status               account_status NOT NULL DEFAULT 'active'
  , must_change_password BOOLEAN        NOT NULL DEFAULT FALSE
  , created_at           TIMESTAMPTZ    NOT NULL DEFAULT NOW()
  , CONSTRAINT uq_admins_email UNIQUE (email)
);

-- one global clinic settings
CREATE TABLE clinic_settings (
    setting_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , clinic_name            VARCHAR(100) NOT NULL
  , time_zone              VARCHAR(50)  NOT NULL
  , near_threshold         INTEGER      NOT NULL DEFAULT 3
  , grace_minutes          INTEGER      NOT NULL DEFAULT 10
  , default_travel_minutes INTEGER      NOT NULL DEFAULT 15
);

-- services table
CREATE TABLE services (
    service_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , service_name        VARCHAR(100) NOT NULL
  , prefix              VARCHAR(3)   NOT NULL
  , description         VARCHAR(255) NULL
  , avg_service_minutes INTEGER      NOT NULL DEFAULT 10
  , open_time           TIME         NOT NULL
  , close_time          TIME         NOT NULL
  , daily_limit         INTEGER      NULL
  , queue_status        queue_status NOT NULL DEFAULT 'open'
  , status_note         VARCHAR(100) NULL
  , is_active           BOOLEAN      NOT NULL DEFAULT TRUE
  , created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
  , CONSTRAINT uq_services_name   UNIQUE (service_name)
  , CONSTRAINT uq_services_prefix UNIQUE (prefix)
);

-- staff services table, which staff works on a service
CREATE TABLE staff_services (
    staff_service_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , counter_label    VARCHAR(30) NOT NULL
  , staff_id         INTEGER     NOT NULL REFERENCES staff (staff_id)      ON DELETE CASCADE
  , service_id       INTEGER     NOT NULL REFERENCES services (service_id) ON DELETE CASCADE
  , CONSTRAINT uq_staff_services_unique UNIQUE (staff_id, service_id)
);

--creates the tickets table
CREATE TABLE tickets (
    ticket_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , queue_date     DATE          NOT NULL
  , queue_number   INTEGER       NOT NULL
  , walk_in_name   VARCHAR(100)  NULL
  , status         ticket_status NOT NULL DEFAULT 'waiting'
  , priority       BOOLEAN       NOT NULL DEFAULT FALSE
  , note           VARCHAR(100)  NULL
  , travel_minutes INTEGER       NULL
  , status_reason  VARCHAR(100)  NULL
  , queued_at      TIMESTAMPTZ   NOT NULL DEFAULT NOW()
  , called_at      TIMESTAMPTZ   NULL
  , arrived_at     TIMESTAMPTZ   NULL
  , completed_at   TIMESTAMPTZ   NULL
  , is_deleted     BOOLEAN       NOT NULL DEFAULT FALSE
  , patient_id     INTEGER       NULL REFERENCES patients (patient_id)      ON DELETE SET NULL
  , staff_id       INTEGER       NULL REFERENCES staff (staff_id)           ON DELETE SET NULL
  , service_id     INTEGER       NOT NULL REFERENCES services (service_id)  ON DELETE RESTRICT
  , CONSTRAINT uq_tickets_queue UNIQUE (service_id, queue_date, queue_number)
  , CONSTRAINT chk_tickets_identity CHECK (patient_id IS NOT NULL OR walk_in_name IS NOT NULL)
);

--indexes for common searches
CREATE INDEX idx_tickets_date    ON tickets (queue_date);
CREATE INDEX idx_tickets_patient ON tickets (patient_id);

--ticket history table which records all actions on a ticket
CREATE TABLE ticket_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , action     history_action NOT NULL
  , reason     VARCHAR(100)   NULL
  , changed_at TIMESTAMPTZ    NOT NULL DEFAULT NOW()
  , ticket_id  INTEGER        NOT NULL REFERENCES tickets (ticket_id)  ON DELETE CASCADE
  , patient_id INTEGER        NULL REFERENCES patients (patient_id)    ON DELETE SET NULL
  , staff_id   INTEGER        NULL REFERENCES staff (staff_id)         ON DELETE SET NULL
  , admin_id   INTEGER        NULL REFERENCES admins (admin_id)        ON DELETE SET NULL
);

--for searching history
CREATE INDEX idx_ticket_history_ticket ON ticket_history (ticket_id);

--notifications to patients
CREATE TABLE notifications (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , type            notification_type NOT NULL
  , message         VARCHAR(150)      NOT NULL
  , is_read         BOOLEAN           NOT NULL DEFAULT FALSE
  , created_at      TIMESTAMPTZ       NOT NULL DEFAULT NOW()
  , patient_id      INTEGER           NOT NULL REFERENCES patients (patient_id) ON DELETE CASCADE
  , ticket_id       INTEGER           NULL REFERENCES tickets (ticket_id)       ON DELETE SET NULL
);

--lookup for notifications
CREATE INDEX idx_notifications_patient ON notifications (patient_id, is_read);

--indexes for foreign keys for faster joins
CREATE INDEX idx_staff_services_service ON staff_services (service_id);
CREATE INDEX idx_tickets_staff          ON tickets (staff_id);
CREATE INDEX idx_ticket_history_admin   ON ticket_history (admin_id);
CREATE INDEX idx_ticket_history_patient ON ticket_history (patient_id);
CREATE INDEX idx_ticket_history_staff   ON ticket_history (staff_id);
CREATE INDEX idx_notifications_ticket   ON notifications (ticket_id);

